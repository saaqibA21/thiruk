const jsonPaths = [
  path.resolve('public/thirukkural.json'),
  path.resolve('thirukkural.json')
];

for (const p of jsonPaths) {
  if (!fs.existsSync(p)) continue;
  const data = JSON.parse(fs.readFileSync(p, 'utf8'));
  
  if (Array.isArray(data.kural)) {
    for (const k of data.kural) {
      if (simpleExplanations[k.Number]) {
        k.simple_explanation = simpleExplanations[k.Number];
      }
    }
  }

  fs.writeFileSync(p, JSON.stringify(data, null, 2), 'utf8');
  console.log(`Updated ${p} with first 10 simple explanations.`);
}
