/**
 * Get Athigaram info for any Kural number
 */
export const getKuralAthigaram = (kuralNumber) => {
  const num = Number(kuralNumber);
  const chapterNum = Math.ceil(num / 10);
  const found = ALL_ATHIGARAMS.find(a => a.n === chapterNum);
  if (found) {
    return {
      chapterNumber: found.n,
      chapterName: found.name,
      chapterEn: found.en,
      paal: found.paal,
      paalEn: found.paalEn,
      kuralIndexInChapter: ((num - 1) % 10) + 1
    };
  }
  return {
    chapterNumber: chapterNum,
    chapterName: 'திருக்குறள் வாழ்வியல்',
    chapterEn: 'Ethical Living',
    paal: 'அறத்துப்பால்',
    paalEn: 'Virtue',
    kuralIndexInChapter: ((num - 1) % 10) + 1
  };
};

